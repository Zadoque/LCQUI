import { test, expect } from "../fixtures";
import { capturarCallable, login, esperarCallable, lerResultadoCallable } from "../helpers/ui";
import { lerDocumento, listarColecao } from "../helpers/emulator";

test("RET-E2E-001: registra retirada com contrato completo", async ({ page, guardaConsole }) => {
  const chamadasBuscaRetirante = capturarCallable(page, "buscarUsuariosParaRetirada");
  const chamadasBuscaLocal = capturarCallable(page, "buscarLocaisParaRetirada");
  await login(page, "gestor.almoxarifado@lcqui.local");
  await page.goto("/reagentes");
  await page.getByPlaceholder("Pesquisar reagente por nome ou tipo químico (começa no 1º caractere)...").fill("Reagente Seed");
  await page.getByText("Reagente Seed", { exact: true }).first().click();
  await page.getByRole("button", { name: "+ Frasco" }).click();
  const entrada = page.locator("form").filter({ hasText: "Salvar Frasco" });
  const entradaNumeros = entrada.locator('input[type="number"]');
  await entradaNumeros.nth(0).fill("500");
  await entradaNumeros.nth(1).fill("250");
  const resposta = esperarCallable(page, "cadastrarFrascoFechado");
  await entrada.getByRole("button", { name: "Salvar Frasco" }).click();
  await resposta;
  await expect(page.getByTestId("frasco-cadastro-sucesso")).toBeVisible();
  await page.getByRole("button", { name: "Concluir" }).click();
  const chave = await lerDocumento("Chaves_Unicas/Frasco_Reagente__LCQUI-1");
  expect(chave).not.toBeNull();

  await page.getByRole("button", { name: "Registrar Retirada" }).click();
  const formulario = page.locator("form").filter({ has: page.getByRole("button", { name: "Confirmar" }) });
  await formulario.getByLabel("Código do frasco (LCQUI-)").fill(chave!.data.id_recurso as string);
  await formulario.getByTestId("retirada-abrir-seletor").click();
  await page.getByTestId("retirada-modal-seletor").getByLabel("Letra inicial do nome").fill("P");
  const buscaRetirante = esperarCallable(page, "buscarUsuariosParaRetirada");
  await page.getByTestId("retirada-modal-seletor").getByTestId("retirada-buscar").click();
  await buscaRetirante;
  await expect.poll(() => chamadasBuscaRetirante).toHaveLength(1);
  await page.getByTestId("retirada-modal-seletor").getByTestId("retirada-usuario-seed-professor-alpha").click();
  await formulario.getByTestId("retirada-abrir-local").click();
  await page.getByTestId("retirada-modal-local").getByLabel("Prédio do local").fill("Bloco de Química");
  const buscaLocal = esperarCallable(page, "buscarLocaisParaRetirada");
  await page.getByTestId("retirada-buscar-local").click();
  await buscaLocal;
  await expect.poll(() => chamadasBuscaLocal).toHaveLength(1);
  await page.getByTestId("retirada-local-seed-local-almox-frascos").click();
  await formulario.locator('input[type="number"]').fill("500");
  await formulario.locator('input[type="date"]').fill("2099-01-01");
  await formulario.getByLabel("Abrir o frasco no empréstimo").check();
  const chamada = esperarCallable(page, "registrarRetirada");
  const confirmarRetirada = formulario.getByRole("button", { name: "Confirmar" });
  await confirmarRetirada.evaluate((element) => element.scrollIntoView({ block: "center", inline: "nearest" }));
  await confirmarRetirada.dispatchEvent("click");
  const retorno = await chamada;
  expect(retorno.status()).toBe(200);
  await expect(page.getByRole("heading", { name: "Catálogo de Reagentes" })).toBeVisible();
  const emprestimos = await listarColecao("Emprestimo_Reagente");
  expect(emprestimos.some((item) => item.data.id_frasco_reagente === chave!.data.id_recurso && item.data.status === "EM_USO")).toBe(true);
  const frascoAberto = await lerDocumento(`Frasco_Reagente/${chave!.data.id_recurso}`);
  expect(frascoAberto?.data.estado_fisico_frasco).toBe("ABERTO");
  expect(frascoAberto?.data.data_abertura).toBeTruthy();

  guardaConsole.permitir(/400/);
  await page.getByRole("button", { name: "Registrar Retirada" }).click();
  const segunda = page.locator("form").filter({ has: page.getByRole("button", { name: "Confirmar" }) });
  await segunda.getByLabel("Código do frasco (LCQUI-)").fill(chave!.data.id_recurso as string);
  await segunda.getByTestId("retirada-abrir-seletor").click();
  await page.getByTestId("retirada-modal-seletor").getByLabel("Letra inicial do nome").fill("P");
  await page.getByTestId("retirada-modal-seletor").getByTestId("retirada-buscar").click();
  await expect.poll(() => chamadasBuscaRetirante).toHaveLength(1);
  await page.getByTestId("retirada-modal-seletor").getByTestId("retirada-usuario-seed-professor-alpha").click();
  await segunda.getByTestId("retirada-abrir-local").click();
  await page.getByTestId("retirada-modal-local").getByLabel("Prédio do local").fill("Bloco de Química");
  await page.getByTestId("retirada-buscar-local").click();
  await expect.poll(() => chamadasBuscaLocal).toHaveLength(1);
  await page.getByTestId("retirada-local-seed-local-almox-frascos").click();
  await segunda.locator('input[type="number"]').fill("500");
  await segunda.locator('input[type="date"]').fill("2099-01-01");
  const segundaChamada = esperarCallable(page, "registrarRetirada");
  const confirmarSegunda = segunda.getByRole("button", { name: "Confirmar" });
  await confirmarSegunda.evaluate((element) => element.scrollIntoView({ block: "center", inline: "nearest" }));
  await confirmarSegunda.dispatchEvent("click");
  const segundaResposta = await segundaChamada;
  expect(segundaResposta.status()).toBe(400);
  await expect(page.getByText(/não está disponível/i)).toBeVisible();
});

test("DEV-001-E2E-002: conclui retirada e devolução com pesagens concordantes", async ({ page }) => {
  await login(page, "gestor.almoxarifado@lcqui.local");
  await page.goto("/reagentes");
  await page.getByPlaceholder("Pesquisar reagente por nome ou tipo químico (começa no 1º caractere)...").fill("Reagente Seed");
  await page.getByText("Reagente Seed", { exact: true }).first().click();
  await page.getByRole("button", { name: "+ Frasco" }).click();
  const entrada = page.locator("form").filter({ hasText: "Salvar Frasco" });
  const entradaNumeros = entrada.locator('input[type="number"]');
  await entradaNumeros.nth(0).fill("500");
  await entradaNumeros.nth(1).fill("250");
  const criar = esperarCallable(page, "cadastrarFrascoFechado");
  await entrada.getByRole("button", { name: "Salvar Frasco" }).click();
  const resultado = await lerResultadoCallable(await criar);
  const frascoId = resultado.idFrasco as string;
  expect(frascoId).toBeTruthy();
  await expect(page.getByTestId("frasco-cadastro-sucesso")).toBeVisible();
  await page.getByRole("button", { name: "Concluir" }).click();
  const frascoCriado = await lerDocumento(`Frasco_Reagente/${frascoId}`);
  expect(frascoCriado).toBeTruthy();
  const codigoFrasco = frascoCriado!.data.codigo_frasco as string;

  await page.getByRole("button", { name: "Registrar Retirada" }).click();
  const retirada = page.locator("form").filter({ has: page.getByRole("button", { name: "Confirmar" }) });
  await retirada.getByLabel("Código do frasco (LCQUI-)").fill(frascoId);
  await retirada.getByTestId("retirada-abrir-seletor").click();
  await page.getByTestId("retirada-modal-seletor").getByLabel("Letra inicial do nome").fill("P");
  const buscaRetirante = esperarCallable(page, "buscarUsuariosParaRetirada");
  await page.getByTestId("retirada-modal-seletor").getByTestId("retirada-buscar").click();
  await buscaRetirante;
  await page.getByTestId("retirada-modal-seletor").getByTestId("retirada-usuario-seed-professor-alpha").click();
  await retirada.getByTestId("retirada-abrir-local").click();
  await page.getByTestId("retirada-modal-local").getByLabel("Prédio do local").fill("Bloco de Química");
  const retiradaBuscaLocal = esperarCallable(page, "buscarLocaisParaRetirada");
  await page.getByTestId("retirada-buscar-local").click();
  await retiradaBuscaLocal;
  await page.getByTestId("retirada-local-seed-local-almox-frascos").click();
  await retirada.locator('input[type="number"]').fill("500");
  await retirada.locator('input[type="date"]').fill("2099-01-01");
  await retirada.getByLabel("Abrir o frasco no empréstimo").check();
  const retiradaCall = esperarCallable(page, "registrarRetirada");
  const confirmarRetirada = retirada.getByRole("button", { name: "Confirmar" });
  await confirmarRetirada.evaluate((element) => element.scrollIntoView({ block: "center", inline: "nearest" }));
  await confirmarRetirada.dispatchEvent("click");
  await retiradaCall;

  await page.goto("/reagentes/seed-resumo-reagente-frascos");
  const linhaFrasco = page.locator("tbody tr").filter({ hasText: codigoFrasco }).last();
  await expect(linhaFrasco.getByRole("button", { name: "Devolver" }).last()).toBeVisible();
  await linhaFrasco.getByRole("button", { name: "Devolver" }).last().click();
  const devolucao = page.getByRole("heading", { name: "Registrar Devolução" }).locator("..");
  const emprestimosAtivos = await listarColecao("Emprestimo_Reagente");
  const emprestimoAtivo = emprestimosAtivos.find((item) => item.data.id_frasco_reagente === frascoId && item.data.status === "EM_USO");
  expect(emprestimoAtivo).toBeTruthy();
  await devolucao.getByLabel("Código do frasco ou empréstimo *").fill(emprestimoAtivo!.id);
  await devolucao.getByTestId("devolucao-abrir-seletor").click();
  await page.getByTestId("devolucao-modal-seletor").getByLabel("Letra inicial do nome").fill("P");
  const buscaDevolvente = esperarCallable(page, "buscarUsuariosParaRetirada");
  await page.getByTestId("devolucao-modal-seletor").getByTestId("devolucao-buscar").click();
  await buscaDevolvente;
  await page.getByTestId("devolucao-modal-seletor").getByTestId("devolucao-usuario-seed-professor-alpha").click();
  const pesos = devolucao.locator('input[type="number"]');
  await pesos.nth(0).fill("500");
  await pesos.nth(1).fill("500");
  const devolucaoCall = esperarCallable(page, "registrarDevolucao");
  const confirmarDevolucao = devolucao.getByRole("button", { name: "Confirmar Devolução" });
  await confirmarDevolucao.evaluate((element) => element.scrollIntoView({ block: "center", inline: "nearest" }));
  await confirmarDevolucao.dispatchEvent("click");
  const resposta = await devolucaoCall;
  expect(resposta.status()).toBe(200);
  await expect.poll(async () => (await lerDocumento(`Frasco_Reagente/${frascoId}`))?.data.disponibilidade).toBe("DISPONIVEL");
  const linhaAtualizada = page.getByTestId(`frasco-row-${frascoId}`);
  await expect(linhaAtualizada.getByText("ABERTO", { exact: true })).toBeVisible();
  await expect(linhaAtualizada.getByRole("button", { name: "Devolver" })).toHaveCount(0);
});
